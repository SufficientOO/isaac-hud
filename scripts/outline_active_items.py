#!/usr/bin/env python3
"""Generate white-outlined copies of the ACTIVE item sprites.

The vanilla HUD draws the top-left active item with a white outline around
its silhouette (baked in-engine by the game). We reproduce it like
outline_hearts.py: dilate the solid alpha (>=128) by 2px (2x scale = 1
native px) and paint the ring white, original pixels kept on top.

Reads items.xml (extracted game data) for collectibles with
maxcharges > 0, outlines each existing sprite from
assets/sprites/collectibles/ into assets/sprites/collectibles_outlined/,
and (re)generates src/activeItemSprites.ts (id -> require map).

Usage: python3 scripts/outline_active_items.py <extracted_resources_dir>
Run from the repository root.
"""
import os
import sys
import xml.etree.ElementTree as ET

import numpy as np
from PIL import Image

SRC = "assets/sprites/collectibles"
OUT = "assets/sprites/collectibles_outlined"
TS_OUT = "src/activeItemSprites.ts"


def outline(img: Image.Image, thickness: int = 1) -> Image.Image:
    # thickness is in SOURCE pixels: these sprites are native-res (32x32,
    # rendered at 2x), so 1px here matches vanilla's outline; the hearts
    # script uses 2 because its inputs are pre-scaled 2x.
    a = np.array(img.convert("RGBA"))
    # Solid artwork only (>=128) so the ring hugs the silhouette instead of
    # semi-transparent glow/shadow pixels some item sprites carry.
    solid = a[..., 3] >= 128
    dil = solid.copy()
    for _ in range(thickness):
        d = dil.copy()
        d[1:, :] |= dil[:-1, :]
        d[:-1, :] |= dil[1:, :]
        d[:, 1:] |= dil[:, :-1]
        d[:, :-1] |= dil[:, 1:]
        dil = d
    ring = dil & ~solid
    out = a.copy()
    out[ring] = [255, 255, 255, 255]
    return Image.fromarray(out, "RGBA")


def main():
    if len(sys.argv) < 2:
        print("usage: outline_active_items.py <extracted_resources_dir>")
        sys.exit(1)
    res = sys.argv[1]
    root = ET.parse(os.path.join(res, "items.xml")).getroot()

    # Active items = collectibles that hold charges
    active_ids = set()
    for el in root.iter():
        if int(el.get("maxcharges", "0") or 0) > 0:
            active_ids.add(int(el.get("id")))

    # Map id -> existing sprite filename via the leading number in the name
    files = {}
    for fn in os.listdir(SRC):
        if fn.endswith(".png") and fn.startswith("collectibles_"):
            try:
                num = int(fn.split("_")[1])
            except ValueError:
                continue
            files[num] = fn

    os.makedirs(OUT, exist_ok=True)
    entries = []
    for item_id in sorted(active_ids):
        fn = files.get(item_id)
        if not fn:
            print("skip (no sprite):", item_id)
            continue
        outline(Image.open(os.path.join(SRC, fn))).save(os.path.join(OUT, fn))
        entries.append((item_id, fn))

    with open(TS_OUT, "w") as f:
        f.write(
            "// Auto-generated by scripts/outline_active_items.py — do not edit.\n"
            "// White-outlined sprites (vanilla HUD look) for ACTIVE items only\n"
            "// (items.xml maxcharges > 0). Fallback for anything else is the\n"
            "// plain sprite (see collectibleSprites.ts).\n\n"
            "import { ImageSourcePropType } from 'react-native';\n\n"
            "export const ACTIVE_ITEM_SPRITES: Record<number, ImageSourcePropType> = {\n"
        )
        for item_id, fn in entries:
            f.write(f'  {item_id}: require("../assets/sprites/collectibles_outlined/{fn}"),\n')
        f.write("};\n")

    print(f"outlined {len(entries)} active item sprites -> {OUT}/")
    print(f"wrote {TS_OUT} ({len(entries)} entries)")


if __name__ == "__main__":
    main()
